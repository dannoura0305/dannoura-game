# 口先を短く（2026-11-07 正面の表情リスト: 目の下から短く尖る）。目より前（s > 0.1）の前後の位置を縮める
def _shorten(fc, s0=0.1, k=0.84):
    f = lambda v: v if v <= s0 else s0 + (v - s0) * k
    for key in ('w', 'c', 'ht', 'hb', 'p'):
        fc['skull'][key] = [[f(a), b] for a, b in fc['skull'][key]]
    fc['skull']['s1'] = f(fc['skull']['s1'])
    for b in fc['skull']['bumps']:
        b['s'] = f(b['s'])
    for key in ('w', 'd'):
        fc['jaw'][key] = [[f(a), b] for a, b in fc['jaw'][key]]
    fc['jaw']['s1'] = f(fc['jaw']['s1'])
    for b in fc['jaw'].get('bumps', []):
        b['s'] = f(b['s'])
    fc['face_tex']['white_th'] = [[f(a), b] for a, b in fc['face_tex']['white_th']]
    for r in fc['regions'].values():
        if 's' in r:
            r['s'] = f(r['s'])
        if 'pt' in r:
            r['pt'][1] = f(r['pt'][1])
    for sp in fc.get('jaw_spikes', []):
        sp['s'] = f(sp['s'])
    t = fc['teeth']; t['from'], t['to'], t['fang'] = f(t['from']), f(t['to']), f(t['fang'])
    fc['tongue']['c'][1] = f(fc['tongue']['c'][1]); fc['tongue']['ax'][1] *= k
